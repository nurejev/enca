// ======================================================================
// 🚀 Deploy — the script where no API exists (js/pimscript.js, 4.1, build 32510)
//
// Browser first. Where a workload has no Graph write — Exchange and Purview
// role group membership, the regional Exchange scopes until the Exchange
// provider write is consented — Deploy creates the groups it can and offers
// a downloadable PowerShell script that performs the remaining actions with
// the tenant's object ids filled in. The script writes an outcome file
// (JSON) that Deploy reads back to mark each binding verified (Mihai,
// 12 Oct 2026: "where enca offers the object create downloadable ps script
// which can perform the actions"). The maintenance scripts in tools/pim
// stay out of customer screens; this one is generated per tenant.
//
// Pure: no DOM, no Graph. Tested in tools/pimscript.test.cjs.
//   PimScript.forPlan(cat, res, lookup, opts) → [{ kind, label, file, text,
//       entries: [{ group, groupId, target, kind }] }]
//   PimScript.readOutcome(text) → { ok, kind, tenant, ran, results, summary }
// Secrets never appear: the script carries display names, object ids and a
// tenant domain, nothing else — a test asserts it.
// ======================================================================
const PimScript = (() => {
  const esc = (s) => String(s == null ? "" : s).replace(/'/g, "''");
  const ts = (d) => (d || new Date()).toISOString().replace(/[-:]/g, "").replace(/\..+$/, "Z");
  const header = (title, lines, cat) => [
    `# ${title}`,
    `# Generated by ENCA PimBuddy for ${lines.tenant || "<tenant>"} on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC`,
    `# Catalog: ${cat ? `${cat.label} ${cat.release}` : "CloudFellows PIM framework"}`,
    `# This script carries display names and object ids only. It writes an outcome file next to itself;`,
    `# import that file in 🚀 Deploy (Import outcome) so the bindings count as verified.`,
    `# Run it as an administrator who holds the Exchange (or Purview) Role Management permission.`,
    `#Requires -Version 7`,
    "",
  ];
  const outcomeTail = (kind, lines) => [
    "",
    `$outcome = [ordered]@{ kind = '${kind}'; tenant = '${esc(lines.tenant)}'; generatedBy = 'ENCA PimBuddy'; ran = (Get-Date).ToUniversalTime().ToString('o'); results = $results }`,
    `$file = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) ('pim-${kind}-outcome.' + '${esc(lines.tenant || "tenant")}' + '.' + (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss') + '.json')`,
    `$outcome | ConvertTo-Json -Depth 5 | Set-Content -Path $file -Encoding UTF8`,
    `Write-Host "Outcome written to $file — import it in ENCA (🚀 Deploy, Import outcome)."`,
    `$failed = @($results | Where-Object { $_.status -eq 'failed' }).Count`,
    `if ($failed) { Write-Warning "$failed binding(s) failed — see the outcome file." }`,
  ];
  // Role group membership (Exchange Online or Purview): one Add-RoleGroupMember per entry.
  function roleGroupScript(kind, entries, lines, cat) {
    const connect = kind === "purview"
      ? [`Import-Module ExchangeOnlineManagement -ErrorAction Stop`, `Connect-IPPSSession -ShowBanner:$false${lines.tenant ? ` -Organization '${esc(lines.tenant)}'` : ""}`]
      : [`Import-Module ExchangeOnlineManagement -ErrorAction Stop`, `Connect-ExchangeOnline -ShowBanner:$false${lines.tenant ? ` -Organization '${esc(lines.tenant)}'` : ""}`];
    const L = header(kind === "purview" ? "PimBuddy — Purview role group membership" : "PimBuddy — Exchange Online role group membership", lines, cat);
    L.push(...connect, "", "$results = @()",
      "$bindings = @(");
    entries.forEach((e) => L.push(`  @{ roleGroup = '${esc(e.target)}'; member = '${esc(e.group)}'; memberId = ${e.groupId ? `'${esc(e.groupId)}'` : "$null"} }`));
    L.push(")", "",
      "foreach ($b in $bindings) {",
      "  $id = if ($b.memberId) { $b.memberId } else { $b.member }",
      "  if (-not $b.memberId) { Write-Warning \"$($b.member): no object id was known when this script was generated — resolving by name; create the group first (🚀 Deploy) if this fails.\" }",
      "  try {",
      "    $present = @(Get-RoleGroupMember -Identity $b.roleGroup -ErrorAction Stop | Where-Object { ($_.ExternalDirectoryObjectId -and $_.ExternalDirectoryObjectId -eq $b.memberId) -or $_.Name -eq $b.member -or $_.DisplayName -eq $b.member })",
      "    if ($present.Count) { $results += [ordered]@{ roleGroup = $b.roleGroup; member = $b.member; memberId = $b.memberId; status = 'present'; error = $null }; Write-Host \"$($b.member) is already in $($b.roleGroup)\"; continue }",
      "    Add-RoleGroupMember -Identity $b.roleGroup -Member $id -Confirm:$false -ErrorAction Stop",
      "    $check = @(Get-RoleGroupMember -Identity $b.roleGroup -ErrorAction Stop | Where-Object { ($_.ExternalDirectoryObjectId -and $_.ExternalDirectoryObjectId -eq $b.memberId) -or $_.Name -eq $b.member -or $_.DisplayName -eq $b.member })",
      "    $results += [ordered]@{ roleGroup = $b.roleGroup; member = $b.member; memberId = $b.memberId; status = $(if ($check.Count) { 'added' } else { 'failed' }); error = $(if ($check.Count) { $null } else { 'added but not read back' }) }",
      "    Write-Host \"$($b.member) → $($b.roleGroup): $($results[-1].status)\"",
      "  } catch {",
      "    $results += [ordered]@{ roleGroup = $b.roleGroup; member = $b.member; memberId = $b.memberId; status = 'failed'; error = $_.Exception.Message }",
      "    Write-Warning \"$($b.member) → $($b.roleGroup): $($_.Exception.Message)\"",
      "  }",
      "}",
      ...outcomeTail(kind, lines));
    return L.join("\n") + "\n";
  }
  // Regional Exchange: direct management role assignments scoped to the
  // region's user unit — the Graph write needs RoleManagement.ReadWrite.Exchange,
  // which Deploy does not ask for yet (4.1); until then this script.
  function regionalScript(entries, lines, cat) {
    const L = header("PimBuddy — regional Exchange role assignments (scoped to the region's user unit)", lines, cat);
    L.push(`Import-Module ExchangeOnlineManagement -ErrorAction Stop`, `Connect-ExchangeOnline -ShowBanner:$false${lines.tenant ? ` -Organization '${esc(lines.tenant)}'` : ""}`, "", "$results = @()", "$bindings = @(");
    entries.forEach((e) => (e.roles || []).forEach((role) => L.push(`  @{ role = '${esc(role)}'; group = '${esc(e.group)}'; groupId = ${e.groupId ? `'${esc(e.groupId)}'` : "$null"}; unit = '${esc(e.au)}'; unitId = ${e.auId ? `'${esc(e.auId)}'` : "$null"}; name = '${esc(`${e.group}-${role}`.replace(/[^A-Za-z0-9-]/g, ""))}' }`)));
    L.push(")", "",
      "foreach ($b in $bindings) {",
      "  $gid = if ($b.groupId) { $b.groupId } else { $b.group }",
      "  $uid = if ($b.unitId) { $b.unitId } else { $b.unit }",
      "  try {",
      "    $have = @(Get-ManagementRoleAssignment -RoleAssignee $gid -Role $b.role -ErrorAction SilentlyContinue | Where-Object { $_.RecipientAdministrativeUnitScope -and ($_.RecipientAdministrativeUnitScope -eq $uid -or $_.RecipientAdministrativeUnitScope -eq $b.unit) })",
      "    if ($have.Count) { $results += [ordered]@{ role = $b.role; group = $b.group; groupId = $b.groupId; unit = $b.unit; status = 'present'; error = $null }; continue }",
      "    New-ManagementRoleAssignment -Name $b.name -Role $b.role -SecurityGroup $gid -RecipientAdministrativeUnitScope $uid -ErrorAction Stop | Out-Null",
      "    $results += [ordered]@{ role = $b.role; group = $b.group; groupId = $b.groupId; unit = $b.unit; status = 'added'; error = $null }",
      "    Write-Host \"$($b.group) ← $($b.role) @ $($b.unit): added\"",
      "  } catch {",
      "    $results += [ordered]@{ role = $b.role; group = $b.group; groupId = $b.groupId; unit = $b.unit; status = 'failed'; error = $_.Exception.Message }",
      "    Write-Warning \"$($b.group) ← $($b.role) @ $($b.unit): $($_.Exception.Message)\"",
      "  }",
      "}",
      ...outcomeTail("exchange-regional", lines));
    return L.join("\n") + "\n";
  }
  // The scripts a plan needs. res = PimBaseline.compare result (groups with
  // scope/exchange/purview), lookup(name) → object id or null, opts:
  // { domain, regions: [PimBaseline.region(...)], on(section) → bool, au(name) → id }.
  function forPlan(cat, res, lookup, opts = {}) {
    const on = opts.on || (() => true);
    const id = (n) => { try { const v = lookup ? lookup(n) : null; return v && !String(v).startsWith("{{") ? String(v) : null; } catch { return null; } };
    const lines = { tenant: opts.domain || "" };
    const out = [];
    const exo = (res.groups || []).filter((g) => g.scope === "exchange" && g.exchange && g.exchange.roleGroup);
    if (on("exchange") && exo.length) {
      const entries = exo.map((g) => ({ kind: "exchange", group: g.name, groupId: id(g.name), target: g.exchange.roleGroup }));
      out.push({ kind: "exchange", label: "Exchange role groups", file: `pim-exchange.${lines.tenant || "tenant"}.ps1`, entries, text: roleGroupScript("exchange", entries, lines, cat) });
    }
    const pur = (res.groups || []).filter((g) => g.scope === "purview" && g.purview && g.purview.roleGroup);
    if (on("purview") && pur.length) {
      const entries = pur.map((g) => ({ kind: "purview", group: g.name, groupId: id(g.name), target: g.purview.roleGroup }));
      out.push({ kind: "purview", label: "Purview role groups", file: `pim-purview.${lines.tenant || "tenant"}.ps1`, entries, text: roleGroupScript("purview", entries, lines, cat) });
    }
    const regs = (opts.regions || []).filter(Boolean);
    const rentries = [];
    if (on("regions")) regs.forEach((R) => (R.groups || []).filter((g) => g.exchange && Array.isArray(g.exchange.roles)).forEach((g) => rentries.push({ kind: "exchange-regional", group: g.name, groupId: id(g.name), au: g.exchange.au, auId: opts.au ? (opts.au(g.exchange.au) || null) : null, roles: g.exchange.roles, target: `${g.exchange.au}` })));
    if (rentries.length) out.push({ kind: "exchange-regional", label: "Regional Exchange scopes", file: `pim-exchange-regional.${lines.tenant || "tenant"}.ps1`, entries: rentries, text: regionalScript(rentries, lines, cat) });
    return out;
  }
  // The outcome file the script wrote. Never trusted beyond its shape: a
  // status is one of present / added / failed, everything else is text.
  function readOutcome(text) {
    let o;
    try { o = typeof text === "string" ? JSON.parse(text) : text; } catch { return { ok: false, error: "not JSON" }; }
    if (!o || typeof o !== "object" || !Array.isArray(o.results)) return { ok: false, error: "no results array" };
    const kind = String(o.kind || "");
    if (!/^(exchange|purview|exchange-regional)$/.test(kind)) return { ok: false, error: `unknown kind ${kind || "(none)"}` };
    const results = o.results.map((r) => ({
      target: String(r.roleGroup || r.unit || ""), role: r.role ? String(r.role) : null, group: String(r.member || r.group || ""), groupId: r.memberId || r.groupId || null,
      status: /^(present|added|failed)$/.test(String(r.status)) ? String(r.status) : "unknown", error: r.error ? String(r.error).slice(0, 300) : null,
    }));
    const summary = { present: 0, added: 0, failed: 0, unknown: 0 };
    results.forEach((r) => { summary[r.status] = (summary[r.status] || 0) + 1; });
    return { ok: true, kind, tenant: String(o.tenant || ""), ran: String(o.ran || ""), results, summary, verified: results.filter((r) => r.status !== "failed" && r.status !== "unknown").map((r) => `${r.group}→${r.target}${r.role ? `:${r.role}` : ""}`) };
  }
  return { forPlan, readOutcome, roleGroupScript, regionalScript };
})();
