// node --test tools/locinventory.test.cjs — T15 ⭳ Locations only (1.12.0,
// 33305, Mihai 11 Nov: "export location and ip only, not with the policies
// attached"): the inventory in three formats and nothing about policies.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs"), path = require("path");
const read = (p) => fs.readFileSync(path.join(__dirname, "..", p), "utf8");
const Loc = new Function(read("js/causes.js") + ";" + read("js/locations.js") + ";return Locations;")();
const IP = "#microsoft.graph.ipNamedLocation", CTRY = "#microsoft.graph.countryNamedLocation", CN = "#microsoft.graph.compliantNetworkNamedLocation";
const locs = [
  { "@odata.type": IP, id: "hq", displayName: "Corporate HQ", isTrusted: true, ipRanges: [{ cidrAddress: "203.0.113.0/24" }, { cidrAddress: "198.51.100.7/32" }] },
  { "@odata.type": IP, id: "ns", displayName: "Netskope, egress", isTrusted: false, ipRanges: [{ cidrAddress: "2001:db8::/32" }] },
  { "@odata.type": CTRY, id: "eu", displayName: "Allowed EU countries", countriesAndRegions: ["NL", "BE"], includeUnknownCountriesAndRegions: true },
  { "@odata.type": CN, id: "cn", displayName: "All Compliant Network locations" },
];

test("CSV per IP range: one row per range, countries on the country row, sorted by name, quoted where needed", () => {
  const rows = Loc.inventoryCsv(locs, "range").split("\r\n");
  assert.equal(rows[0], "name,type,trusted,ip_range,countries");
  assert.deepEqual(rows.slice(1), [
    "All Compliant Network locations,compliantNetwork,,,",
    "Allowed EU countries,country,,,\"BE; NL\"",
    "Corporate HQ,ip,true,198.51.100.7/32,",
    "Corporate HQ,ip,true,203.0.113.0/24,",
    "\"Netskope, egress\",ip,false,2001:db8::/32,",
  ]);
});

test("CSV per location: one row each, ranges joined, count, lookup and unknown", () => {
  const rows = Loc.inventoryCsv(locs, "location").split("\r\n");
  assert.equal(rows[0], "name,type,trusted,ip_ranges,range_count,countries,country_lookup,include_unknown");
  assert.equal(rows.length, 5);
  assert.ok(rows.includes("Corporate HQ,ip,true,\"198.51.100.7/32; 203.0.113.0/24\",2,,,"));
  assert.ok(rows.includes("Allowed EU countries,country,,,,\"BE; NL\",clientIpAddress,true"));
});

test("Markdown: the table and the counts, no policy or findings column, says what was left out", () => {
  const md = Loc.inventoryMd(locs.slice(0, 3), { tenant: "Contoso", of: 4, generatedBy: "Generated by ENCA" });
  assert.match(md, /^# Named locations — Contoso/);
  assert.match(md, /3 locations \(the 3 shown of 4\) — 2 IP \(3 ranges\), 1 country/);
  assert.match(md, /\| Name \| Type \| Trusted \| IP ranges \/ countries \|/);
  assert.match(md, /\| Corporate HQ \| IP \| yes \| 198\.51\.100\.7\/32, 203\.0\.113\.0\/24 \|/);
  assert.match(md, /\| Allowed EU countries \| Country \| — \| BE, NL \+ unknown \(IP\) \|/);
  assert.doesNotMatch(md, /\| Used by|Findings:|CA\d{3}/);
});

test("the three exports never read policies", () => {
  const src = read("js/locations.js");
  const block = src.slice(src.indexOf("function inventoryCsv"), src.indexOf("return { IP_TYPE"));
  assert.doesNotMatch(block, /usedBy\(|findings\(|trustedConsumers\(|\braws\b/);
});
